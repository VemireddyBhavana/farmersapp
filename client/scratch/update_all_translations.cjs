languages = Object.keys(updates);

languages.forEach(lang => {
  const filePath = path.join('d:', 'projects', 'farmersapp', 'client', 'lib', 'i18n', `${lang}.ts`);
  if (!fs.existsSync(filePath)) return;

  let content = fs.readFileSync(filePath, 'utf8');
  const langUpdates = updates[lang];
  
  // Prepare update block
  let updateLines = "";
  for (const [key, value] of Object.entries(langUpdates)) {
    if (!content.includes(`${key}:`)) {
      updateLines += `    ${key}: ${JSON.stringify(value)},\n`;
    }
  }

  if (updateLines) {
    // Insert before the last closing brace
    content = content.trim();
    if (content.endsWith('};')) {
      content = content.slice(0, -2) + updateLines + '};';
    } else if (content.endsWith('}')) {
      content = content.slice(0, -1) + updateLines + '}';
    }
    fs.writeFileSync(filePath, content);
    console.log(`Updated ${lang}.ts with ${Object.keys(langUpdates).length} keys.`);
  } else {
    console.log(`${lang}.ts is already up to date.`);
  }
});
